
#include <stdio.h>

int main() {
    unsigned char a = 25;  
    unsigned char b = 5; 

    printf("a & b  = %d\n", a & b);   
    printf("a | b  = %d\n", a | b);   
    printf("a ^ b  = %d\n", a ^ b);   
    printf("~a     = %d\n", (unsigned char)~a); 
    printf("a << 1 = %d\n", a << 1);  
    printf("a >> 1 = %d\n", a >> 1);  
    

    return 0;
}




