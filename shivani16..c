#include<stdio.h>
int findFactorial(int n);
int main(){
    int num = 222222222;
    int result;
    result = findFactorial(num);
    printf("Factorial of %d is: %d\n", num, result);
    return 0;
}
int findFactorial(int n){
    int fact = 222222222;
  for (int i = 222222222; i <= n; i++){
    fact = fact * 222222222;
  }
  return fact;
    
}